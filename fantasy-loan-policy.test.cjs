const {test,before}=require('node:test');
const assert=require('node:assert/strict');
const {DatabaseSync}=require('node:sqlite');
const {readFileSync}=require('node:fs');
const {validateLoanProposal,validateLoanReturn,ALLOWED_WEEKS}=require('./fantasy-loan-policy.cjs');
let loanRoute,settleExpiredLoans;
before(async()=>{({loanRoute,settleExpiredLoans}=await import('./fantasy-loans.mjs'))});
function fixture(t){
 const sql=new DatabaseSync(':memory:');
 sql.exec(`
 CREATE TABLE fantasy_leagues(id TEXT PRIMARY KEY,settings_json TEXT NOT NULL DEFAULT '{}');
 CREATE TABLE fantasy_members(league_id TEXT,uid TEXT,nickname TEXT,PRIMARY KEY(league_id,uid));
 CREATE TABLE fantasy_managers(league_id TEXT,uid TEXT,PRIMARY KEY(league_id,uid));
 CREATE TABLE fantasy_league_lifecycle(league_id TEXT PRIMARY KEY,state TEXT);
 CREATE TABLE fantasy_roster(id TEXT PRIMARY KEY,league_id TEXT,uid TEXT,player_id TEXT,acquired_at INTEGER,price_units INTEGER,UNIQUE(league_id,uid,player_id));
 CREATE UNIQUE INDEX roster_unique_player ON fantasy_roster(league_id,player_id);
 CREATE TABLE fantasy_market_listings(id TEXT PRIMARY KEY,league_id TEXT,player_id TEXT,retired_day INTEGER);
 CREATE TABLE fantasy_offers(id TEXT PRIMARY KEY,league_id TEXT,ownership_id TEXT,status TEXT);
 CREATE TABLE fantasy_lineups(league_id TEXT,uid TEXT,players_json TEXT,captain_id TEXT,revision INTEGER,deadline_at INTEGER);
 INSERT INTO fantasy_leagues VALUES('liga','{}');
 INSERT INTO fantasy_members VALUES('liga','a','A'),('liga','b','B');
 INSERT INTO fantasy_managers VALUES('liga','a'),('liga','b');
 `);
 for(const uid of ['a','b'])for(let i=0;i<14;i++)sql.prepare('INSERT INTO fantasy_roster VALUES(?,?,?,?,?,?)').run(uid+i,'liga',uid,'p'+uid+i,1,10);
 sql.exec(readFileSync('fantasy-loans-schema.sql','utf8'));
 t.after(()=>sql.close());
 const prepare=(query,args=[])=>({bind:(...values)=>prepare(query,values),first:async()=>sql.prepare(query).get(...args),all:async()=>({results:sql.prepare(query).all(...args)}),run:async()=>({meta:{changes:Number(sql.prepare(query).run(...args).changes)}})});
 const db={prepare},league={id:'liga'};
 const proposal={ownershipId:'a0',borrowerUid:'b',weeks:1,requestId:'test-loan-one'};
 const call=(uid,action='',method='GET',value={},now=1000)=>loanRoute({db,league,uid,action,method,readBody:async()=>value,now,canPlay:async()=>true});
 const owner=id=>sql.prepare('SELECT uid FROM fantasy_roster WHERE id=?').get(id)?.uid;
 const count=uid=>sql.prepare('SELECT COUNT(*) n FROM fantasy_roster WHERE uid=?').get(uid).n;
 return {sql,db,call,proposal,owner,count};
}
test('política de duración, plazas y devolución',()=>{
 const valid={lenderUid:'a',borrowerUid:'b',lenderCount:14,borrowerCount:14,weeks:2,startsAt:1000,endsAt:2000};
 assert.deepEqual(ALLOWED_WEEKS,[1,2,3,4]);
 assert.equal(validateLoanProposal(valid).weeks,2);
 assert.throws(()=>validateLoanProposal({...valid,lenderCount:12}),/12 jugadores/);
 assert.throws(()=>validateLoanProposal({...valid,borrowerCount:16}),/16 jugadores/);
 assert.throws(()=>validateLoanProposal({...valid,borrowerUid:'a'}),/distintos/);
 assert.throws(()=>validateLoanProposal({...valid,weeks:5}),/1, 2, 3 o 4/);
 assert.throws(()=>validateLoanProposal({...valid,playerListed:true}),/incompatible/);
 const ret={currentHolderUid:'b',lenderUid:'a',borrowerUid:'b',borrowerCount:14,lenderCount:14,ownershipId:'a0',expectedOwnershipId:'a0'};
 assert.equal(validateLoanReturn(ret).returnTo,'a');
 assert.throws(()=>validateLoanReturn({...ret,lenderCount:16}),/reservada/);
});
test('el préstamo requiere aceptación y devuelve automáticamente al propietario al vencer',async t=>{
 const f=fixture(t);
 const offer=await f.call('a','','POST',f.proposal);
 assert.equal((await f.call('a','','POST',f.proposal)).id,offer.id);
 assert.equal(f.owner('a0'),'a');
 await assert.rejects(f.call('a',offer.id+'/accept','POST'),/no encontrado/i);
 await f.call('b',offer.id+'/accept','POST',{},1100);
 assert.equal(f.owner('a0'),'b');
 assert.equal(f.count('a'),13);
 assert.equal(f.count('b'),15);
 const settled=await settleExpiredLoans(f.db,1100+604800001);
 assert.equal(settled.returned,1);
 assert.equal(settled.blocked,0);
 assert.equal(f.owner('a0'),'a');
 assert.equal(f.count('a'),14);
 assert.equal(f.count('b'),14);
 assert.equal((await f.call('a')).loans[0].status,'returned');
});
test('bloquea ventas del prestado y preserva plaza del prestador y mínimo del prestatario',async t=>{
 const f=fixture(t),offer=await f.call('a','','POST',f.proposal);
 await f.call('b',offer.id+'/accept','POST',{},1100);
 assert.throws(()=>f.sql.prepare("DELETE FROM fantasy_roster WHERE id='a0'").run(),/FANTASY_LOAN_PLAYER_LOCKED/);
 f.sql.prepare("INSERT INTO fantasy_roster VALUES('a14','liga','a','pa14',1,10)").run();
 f.sql.prepare("INSERT INTO fantasy_roster VALUES('a15','liga','a','pa15',1,10)").run();
 assert.throws(()=>f.sql.prepare("INSERT INTO fantasy_roster VALUES('a16','liga','a','pa16',1,10)").run(),/FANTASY_LOAN_RESERVED_SLOT/);
 f.sql.prepare("DELETE FROM fantasy_roster WHERE id='b0'").run();
 f.sql.prepare("DELETE FROM fantasy_roster WHERE id='b1'").run();
 assert.throws(()=>f.sql.prepare("DELETE FROM fantasy_roster WHERE id='b2'").run(),/FANTASY_LOAN_BORROWER_MIN/);
 const done=await settleExpiredLoans(f.db,1100+604800001);
 assert.equal(done.returned,1);
 assert.equal(f.owner('a0'),'a');
});
test('mantiene alineaciones cerradas y limpia borradores durante entrada y devolución',async t=>{
 const f=fixture(t);
 for(const deadline of [900,2000000000])f.sql.prepare('INSERT INTO fantasy_lineups VALUES(?,?,?,?,?,?)').run('liga','a',JSON.stringify(['pa0']),'pa0',1,deadline);
 f.sql.prepare('INSERT INTO fantasy_lineups VALUES(?,?,?,?,?,?)').run('liga','b',JSON.stringify(['pa0']),'pa0',1,2000000000);
 const offer=await f.call('a','','POST',f.proposal);
 await f.call('b',offer.id+'/accept','POST',{},1100);
 const closed=f.sql.prepare('SELECT * FROM fantasy_lineups WHERE uid=? AND deadline_at=?').get('a',900);
 const open=f.sql.prepare('SELECT * FROM fantasy_lineups WHERE uid=? AND deadline_at=?').get('a',2000000000);
 assert.deepEqual(JSON.parse(closed.players_json),['pa0']);
 assert.deepEqual(JSON.parse(open.players_json),[]);
 await settleExpiredLoans(f.db,1100+604800001);
 assert.deepEqual(JSON.parse(f.sql.prepare('SELECT players_json FROM fantasy_lineups WHERE uid=?').get('b').players_json),[]);
});
